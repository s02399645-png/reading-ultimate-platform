// Generates worker/src/passages.generated.js from every JSON file in worker/passages/.
// Passages are bundled INTO the Worker, so they are never publicly reachable as static files.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'worker');
const files = readdirSync(join(root, 'passages')).filter(f => f.endsWith('.json')).sort();
const problems = [];

for (const f of files) {
  const p = JSON.parse(readFileSync(join(root, 'passages', f), 'utf8'));
  const sids = new Set(p.paragraphs.flatMap(pa => pa.sentences.map(s => s.id)));
  const seen = new Set();
  for (const g of p.groups) for (const q of g.questions) {
    if (seen.has(q.id)) problems.push(`${f}: duplicate question id ${q.id}`);
    seen.add(q.id);
    if (!sids.has(q.evidence)) problems.push(`${f}: ${q.id} evidence "${q.evidence}" is not a sentence id`);
    if (q.options && !q.options.some(o => (g.type === 'mcq' ? o[0] : o) === q.answer)) problems.push(`${f}: ${q.id} answer "${q.answer}" not among options`);
    if (!q.explanation?.en || !q.explanation?.ru) problems.push(`${f}: ${q.id} missing EN/RU explanation`);
  }
  if (f.replace('.json', '') !== p.id) problems.push(`${f}: id "${p.id}" does not match filename`);
}
if (problems.length) { console.error('Passage problems:\n- ' + problems.join('\n- ')); process.exit(1); }

const out = files.map((f, i) => `import p${i} from '../passages/${f}';`).join('\n') +
  `\nexport const PASSAGES = {\n${files.map((f, i) => `  '${f.replace('.json', '')}': p${i}`).join(',\n')}\n};\n`;
writeFileSync(join(root, 'src', 'passages.generated.js'), '// AUTO-GENERATED by scripts/build-passages.mjs — do not edit\n' + out);
console.log(`Bundled ${files.length} passage(s), all checks passed.`);
